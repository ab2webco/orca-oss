import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'

/**
 * Embeds Orca's UI font into a plain TS module so plugin panels can declare it.
 *
 * Why generated instead of fetched: a panel frame is sandboxed without
 * `allow-same-origin`, so it has an opaque origin and cannot resolve the app's
 * bundled font URL. The panel CSP already allows `font-src data:`, so the bytes
 * have to travel inside the shell string. Reading the woff2 at runtime from
 * main is not equivalent: the renderer bundles the font through Vite and
 * packaged builds do not ship `src/` next to main, so a committed module is the
 * only delivery that behaves the same in dev, packaged, and headless serve.
 */

const SCRIPT_DIR = import.meta.dirname
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..', '..')

export const FONT_SOURCE_PATH = 'src/renderer/src/assets/fonts/Geist-Variable.woff2'
export const GENERATED_MODULE_PATH = 'src/shared/plugins/plugin-panel-sans-font.ts'

/** Mirrors the `@font-face` in src/renderer/src/assets/main.css. */
export const FONT_FAMILY = 'Geist'
export const FONT_WEIGHT_RANGE = '100 900'

export async function buildModuleSource() {
  const bytes = await readFile(path.join(REPO_ROOT, FONT_SOURCE_PATH))
  if (bytes.subarray(0, 4).toString('latin1') !== 'wOF2') {
    throw new Error(`${FONT_SOURCE_PATH} is not a woff2 file`)
  }
  return [
    `// GENERATED by config/scripts/generate-panel-font-data-uri.mjs — do not edit.`,
    `// Re-run \`pnpm run generate:panel-font-data-uri\` after replacing ${FONT_SOURCE_PATH}.`,
    ``,
    `/** Family name declared by the panel shell's @font-face, matching main.css. */`,
    `export const PANEL_SANS_FONT_FAMILY = '${FONT_FAMILY}'`,
    ``,
    `/** Variable-font weight range of the embedded file. */`,
    `export const PANEL_SANS_FONT_WEIGHT_RANGE = '${FONT_WEIGHT_RANGE}'`,
    ``,
    `/** Orca's UI font as a data URI: the only font delivery an opaque-origin`,
    ` *  panel frame can load under the panel CSP (\`font-src data:\`). */`,
    `export const PANEL_SANS_FONT_DATA_URI =`,
    `  'data:font/woff2;base64,${bytes.toString('base64')}'`,
    ``
  ].join('\n')
}

export async function writeModule(source) {
  await writeFile(path.join(REPO_ROOT, GENERATED_MODULE_PATH), source, 'utf8')
  console.log(`wrote ${GENERATED_MODULE_PATH} (${source.length} chars)`)
}

export async function verifyModule(source) {
  const current = await readFile(path.join(REPO_ROOT, GENERATED_MODULE_PATH), 'utf8').catch(
    () => null
  )
  if (current !== source) {
    throw new Error(
      `${GENERATED_MODULE_PATH} is stale. Run \`pnpm run generate:panel-font-data-uri\`.`
    )
  }
  console.log(`${GENERATED_MODULE_PATH} is up to date`)
}

async function main() {
  const source = await buildModuleSource()
  await (process.argv.includes('--write') ? writeModule : verifyModule)(source)
}

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error)
    process.exitCode = 1
  })
}

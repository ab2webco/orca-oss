import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import * as esbuild from 'esbuild'

const scriptDir = import.meta.dirname
const mobileRoot = path.resolve(scriptDir, '..')
const entryPath = path.join(scriptDir, 'team-scene-webview-engine-entry.ts')
const outputPath = path.join(
  mobileRoot,
  'src',
  'team-drawer',
  'team-scene-webview-engine.generated.ts'
)
// Why the xterm engine's floor: the same old Android System WebViews draw the band.
const target = 'chrome74'

// Why bundled, not shipped as source: the desktop's Pixel painter and the shared scene director
// (repo-root src/ and the orca-game plugin) run unchanged in the WebView, so the phone draws what
// the desktop draws without a second painter to keep in step.
async function main() {
  const result = await esbuild.build({
    entryPoints: [entryPath],
    bundle: true,
    format: 'iife',
    minify: true,
    platform: 'browser',
    target,
    legalComments: 'none',
    write: false,
    logLevel: 'silent'
  })
  // A literal </script> inside the bundle would close the inline script tag it is embedded in.
  const engineJs = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')
  const source = [
    '// Generated by scripts/build-team-scene-webview-engine.mjs.',
    `// Target: ${target}. Do not edit by hand; regenerate via pnpm postinstall.`,
    `export const TEAM_SCENE_ENGINE_JS = ${JSON.stringify(engineJs)}`,
    ''
  ].join('\n')
  await writeFile(outputPath, source)
}

await main()

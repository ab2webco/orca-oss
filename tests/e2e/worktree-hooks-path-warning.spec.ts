/**
 * Invariant: creating a worktree whose effective hooks dir has no pre-commit, while the repo ships
 * `.husky/pre-commit`, shows a warning toast naming both paths and leaves core.hooksPath as is
 * (ORCA-680).
 * Needs E2E: the toast is the only UI surface for create warnings and must fit every width.
 */

import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import type { Page, TestInfo } from '@stablyai/playwright-test'
import { expect, test } from './helpers/orca-app'
import { waitForSessionReady } from './helpers/store'

const WIDTHS = [1440, 768, 390, 320] as const
const THEMES = ['light', 'dark'] as const

function git(cwd: string, ...args: string[]): string {
  return execFileSync('git', args, { cwd, encoding: 'utf8' }).trim()
}

function seedMismatchedHooksRepo(): string {
  const repo = mkdtempSync(join(tmpdir(), 'orca-e2e-hooks-path-'))
  git(repo, 'init', '-q', '-b', 'main')
  mkdirSync(join(repo, '.husky'))
  writeFileSync(join(repo, '.husky', 'pre-commit'), '#!/bin/sh\nexit 0\n', { mode: 0o755 })
  git(repo, 'add', '-A')
  git(repo, '-c', 'user.name=e2e', '-c', 'user.email=e2e@orca.test', 'commit', '-q', '-m', 'hooks')
  // Why: `.husky/_` is generated by `npm install`, so a fresh worktree never has it.
  git(repo, 'config', 'core.hooksPath', '.husky/_')
  return repo
}

async function setTheme(page: Page, theme: 'light' | 'dark'): Promise<void> {
  await page.evaluate(async (next) => {
    const settings = await window.api.settings.set({ theme: next })
    window.__store?.setState({ settings })
  }, theme)
  await expect
    .poll(async () =>
      page.evaluate(() => (document.documentElement.classList.contains('dark') ? 'dark' : 'light'))
    )
    .toBe(theme)
}

async function setWidth(page: Page, width: number): Promise<void> {
  await page.setViewportSize({ width, height: 900 })
  // Why: a BrowserWindow minWidth can clamp silently, and the screenshot would prove nothing.
  await expect.poll(async () => page.evaluate(() => window.innerWidth)).toBe(width)
}

test('worktree create warns when core.hooksPath skips the shipped pre-commit', async ({
  orcaPage
}, testInfo: TestInfo) => {
  await waitForSessionReady(orcaPage)
  const repo = seedMismatchedHooksRepo()
  let repoId: string | undefined
  try {
    const seededRepoId = await orcaPage.evaluate(async (repoPath) => {
      const added = await window.api.repos.add({ path: repoPath })
      if ('error' in added) {
        throw new Error(added.error)
      }
      return added.repo.id
    }, repo)
    repoId = seededRepoId
    // Why: repos.add echoes a concurrent fetchRepos whose generation guard can drop ours.
    await expect
      .poll(async () =>
        orcaPage.evaluate(async (id) => {
          await window.__store!.getState().fetchRepos()
          return window.__store!.getState().repos.some((candidate) => candidate.id === id)
        }, seededRepoId)
      )
      .toBe(true)
    const result = await orcaPage.evaluate(async (id) => {
      const created = await window.__store!.getState().createWorktree(id, 'hooks-check', 'main')
      return { warning: created.warning ?? null, path: created.worktree.path }
    }, seededRepoId)

    expect(result.warning).toContain('".husky/_"')
    expect(result.warning).toContain('".husky/pre-commit"')
    expect(git(result.path, 'config', '--get', 'core.hooksPath')).toBe('.husky/_')

    const toast = orcaPage
      .locator('[data-sonner-toast]')
      .filter({ hasText: 'created with a warning' })
    await expect(toast).toBeVisible({ timeout: 15_000 })
    await expect(toast).toContainText('.husky/pre-commit')

    for (const width of WIDTHS) {
      await setWidth(orcaPage, width)
      for (const theme of THEMES) {
        await setTheme(orcaPage, theme)
        await expect(toast).toBeInViewport()
        await orcaPage.screenshot({ path: testInfo.outputPath(`toast-${width}-${theme}.png`) })
      }
    }
  } finally {
    if (repoId) {
      await orcaPage.evaluate(async (id) => window.api.repos.remove({ repoId: id }), repoId)
    }
    rmSync(repo, { recursive: true, force: true })
  }
})
